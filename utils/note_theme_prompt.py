# note有料記事のテーマ発掘用プロンプト。{...} の部分に「私のこと」の入力内容が入る。
PROMPT_TEMPLATE = """あなたは、note有料記事の企画を専門とするプロの編集者です。
私は「自分には書けることがない」と思っているnote初心者です。

私の日常や経験の中から、
私自身が気づいていない「売れるテーマ」を掘り起こしてください。

【私のこと】
・経歴/仕事：{career}
・家族/生活：{family}
・毎日やってること/続いてること：{daily}
・過去に悩んで乗り越えたこと：{overcome}
・人からたまに聞かれること/褒められること：{praised}
・昔ハマってたこと/詳しいこと：{hobbies}

【あなたの思考プロセス】※テーマを出す前に、必ずこの順で考えること
1. 私の記述から「本人は当たり前と思っているが、できない人が多いこと」を抜き出す
2. それぞれについて「それができずに困っている人」を具体的に1人想像する(年齢・状況・悩んでいる瞬間まで)
3. その人が「お金を払ってでも解決したい悩み」になっているかを判定する
(例:「毎晩の寝かしつけに2時間かかって自分の時間がない」は払う悩み、「なんとなく部屋がおしゃれじゃない」は払わない悩み)
4. 悩みの浅いもの・娯楽寄りのものは候補から外す

【テーマ提案のルール】
1. テーマ案は7つ。必ず「◯◯の方法」「◯◯のコツ」「◯◯のルール」「◯◯の手順」のように名詞で終わる形にすること。
感想・日記の形(「〜がつらい」「〜をがんばった」)は禁止
2. 数字を入れられるものは入れること(例:「食費を月1万円下げた買い物ルール」)。
ただし私が書いていない数字を捏造しないこと。数字が不明な箇所は【あなたの実数字】と空欄にすること
3. 各テーマに以下をセットで添えること:
- 想定読者:誰が、どんな状況で悩んでいるか(2行)
- 買う理由:なぜその人がお金を払ってでも読みたいか(1〜2行)
- HARM分類:H/A/R/Mのどれに当たるか(H=Health 健康・美容、A=Ambition 夢・将来・キャリア、R=Relation 人間関係、M=Money お金)
- 検索キーワード:noteで競合と相場を確認するための検索ワード(2〜3語)
4. 専門資格や特別な実績がないと書けないテーマは出さないこと。私の実体験だけで書き切れるものに限ること
5. 「誰にでも当てはまる広いテーマ」より「狭くて具体的なテーマ」を優先すること
(例:「時短料理のコツ」ではなく「ワンオペ平日の夕飯を30分で終わらせる段取り」)

【情報が足りない場合】
私の記述が少なすぎてテーマを絞れない場合は、いきなり提案せず、
「過去に一番時間を使って解決したことは?」「人と比べて楽にできてしまうことは?」など、
掘り起こしに必要な質問を2〜3個、私に返してください。

【出力の最後に】
7案を出し終えたら、あなたが編集者として「最も売れる可能性が高い」と思う1つと、その理由を教えてください。

その上で「ピンとこなければ、別の角度からもう7案出します。気になるテーマがあれば、noteでの需要確認の前にターゲットをさらに絞ることもできます」と私に伝えてください。"""

# 「私のこと」の入力項目: (キー, 画面の見出し, 入力例)
PROFILE_FIELDS = [
    ("career", "経歴/仕事", "例: 事務職10年、前職は飲食店の店長"),
    ("family", "家族/生活", "例: 夫と小学生の子ども2人、地方から都内へ転勤"),
    ("daily", "毎日やってること/続いてること", "例: 朝のウォーキング、家計簿、作り置き"),
    ("overcome", "過去に悩んで乗り越えたこと", "例: 産後の体重を戻した、資格試験に落ちた経験"),
    ("praised", "人からたまに聞かれること/褒められること", "例: 段取りがいい、字がきれい"),
    ("hobbies", "昔ハマってたこと/詳しいこと", "例: キャンプ、ビジネス書、保有資格"),
]


def build_prompt(profile: dict) -> str:
    values = {key: profile.get(key, "").strip() or "（記入なし）" for key, _, _ in PROFILE_FIELDS}
    return PROMPT_TEMPLATE.format(**values)
